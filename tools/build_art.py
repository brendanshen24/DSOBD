#!/usr/bin/env python3
"""Compile vector instrument sprites and font masks into ROM assets.

Run with Python 3 + Pillow. Generated C data is checked in, so ROM builds do
not need Python, external files, font rendering, or an SD card at runtime.
"""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
FONT = str(ROOT / "assets/BarlowCondensed-SemiBold.ttf")
TEXT_FONT = str(ROOT / "assets/Barlow-SemiBold.ttf")
arrays = []


def emit(name, values, ctype="uint16_t"):
    values = list(values)
    arrays.append((name, values, ctype))


def rgb555(im):
    return [0 if a < 128 else 0x8000 | (r >> 3) | ((g >> 3) << 5) | ((b >> 3) << 10)
            for r, g, b, a in im.convert("RGBA").getdata()]


# The brushed instrument deck is a formula, so source/dtec_gfx.c computes it at
# startup instead of storing 96 KB in the ARM9 binary (keeps it under 512 KB).

# Original antialiased metal dial sprite, drawn at 3x then reduced once offline.
s = 3
dial = Image.new("RGBA", (176*s, 176*s))
dr = ImageDraw.Draw(dial)
for radius in range(87*s, 0, -1):
    r = radius / s
    if r > 85:
        col = (31, 44, 57, 255)
    elif r > 82:
        v = int(96 + (r - 82) * 27)
        col = (v, min(v+12, 255), min(v+23, 255), 255)
    elif r > 79:
        col = (28, 39, 51, 255)
    else:
        v = int(12 + 9 * (1-r/79))
        col = (v, v+7, v+14, 255)
    dr.ellipse((88*s-radius, 88*s-radius, 88*s+radius, 88*s+radius), fill=col)
dr.arc((5*s, 5*s, 171*s, 171*s), 205, 305, fill=(200, 223, 236, 255), width=s)
emit("dtec_art_dial", rgb555(dial.resize((176, 176), Image.Resampling.LANCZOS)))

# Proportional alpha glyph sprites (like the PSP/3DS Barlow atlases): each glyph
# is drawn left-aligned in a (10*scale) x (8*scale) cell with its own advance.
adv = []
for scale in (1, 2, 3):
    cw, ch_h = 10 * scale, 8 * scale
    font = ImageFont.truetype(TEXT_FONT, 10 * scale * 4)
    values = []
    for ch in map(chr, range(32, 127)):
        glyph = Image.new("L", (cw*4, ch_h*4))
        d = ImageDraw.Draw(glyph)
        d.text((0, 7*scale*4), ch, font=font, anchor="ls", fill=255)
        a = round(d.textlength(ch, font=font) / 4)
        adv.append(min(cw, max(3 * scale if ch == " " else 1, a)))  # Barlow's 2px space vanishes on DS
        glyph = glyph.resize((cw, ch_h), Image.Resampling.LANCZOS)
        values.extend((v+8)//17 for v in glyph.getdata())
    emit(f"dtec_font_{scale}", values, "uint8_t")
emit("dtec_font_adv", adv, "uint8_t")

font = ImageFont.truetype(FONT, 145*3)
values = []
for ch in "0123456789-":
    glyph = Image.new("L", (64*3, 112*3))
    d = ImageDraw.Draw(glyph)
    box = d.textbbox((0, 0), ch, font=font)
    d.text(((64*3-(box[2]-box[0]))/2-box[0], (112*3-(box[3]-box[1]))/2-box[1]),
           ch, font=font, fill=255)
    values.extend((v+8)//17 for v in glyph.resize((64, 112), Image.Resampling.LANCZOS).getdata())
emit("dtec_digits", values, "uint8_t")

header = ["// Generated by tools/build_art.py; do not hand edit.", "#pragma once", "#include <stdint.h>"]
source = ['// Generated by tools/build_art.py; do not hand edit.', '#include "dtec_assets.h"']
for name, data, ctype in arrays:
    header.append(f"extern const {ctype} {name}[{len(data)}];")
    source.append(f"const {ctype} {name}[{len(data)}] __attribute__((aligned(4))) = {{")
    for i in range(0, len(data), 24):
        source.append(",".join(str(v) for v in data[i:i+24]) + ",")
    source.append("};")
(ROOT / "include/dtec_assets.h").write_text("\n".join(header)+"\n")
(ROOT / "source/dtec_assets.c").write_text("\n".join(source)+"\n")
print(f"Compiled {sum(len(d)*(2 if t == 'uint16_t' else 1) for _,d,t in arrays):,} bytes of artwork")
